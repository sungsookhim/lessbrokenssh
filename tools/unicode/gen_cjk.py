#!/usr/bin/env python3
"""Generate cjk.r: Unicode -> Mac Japanese and Mac Korean conversion tables.

The Mac draws Japanese and Korean through its script systems, which take
text in their own double-byte encodings (Shift-JIS and EUC-KR based). These
tables let the app convert without the Text Encoding Converter, so it also
works on systems before Mac OS 8.5.

One 'CJKT' resource per script (128 Japanese, 129 Korean):

    uint16 count
    { uint16 unicode, uint16 code } [count]    sorted by unicode

Only two-byte, full-width characters are included: those are the ones that
take two cells, which is when the app uses a script font.

usage: gen_cjk.py [output.r]
"""

import os
import struct
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))

RANGES = [
    (0x2E80, 0x9FFF),  # CJK radicals, symbols and punctuation, kana, ideographs
    (0xAC00, 0xD7A3),  # Hangul syllables
    (0xF900, 0xFAFF),  # CJK compatibility ideographs
    (0xFE30, 0xFE4F),  # CJK compatibility forms
    (0xFF01, 0xFF60),  # fullwidth ASCII
    (0xFFE0, 0xFFE6),  # fullwidth signs
]

SCRIPTS = [(128, "Japanese", "shift_jis"), (129, "Korean", "euc_kr")]


def table(codec):
    pairs = []
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            try:
                b = chr(cp).encode(codec)
            except UnicodeEncodeError:
                continue
            if len(b) == 2:
                pairs.append((cp, (b[0] << 8) | b[1]))
    return pairs


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "cjk.r")
    parts = ["/* generated by tools/unicode/gen_cjk.py; don't edit */", ""]
    for res_id, name, codec in SCRIPTS:
        pairs = table(codec)
        data = struct.pack(">H", len(pairs)) + b"".join(struct.pack(">HH", u, c) for u, c in pairs)
        parts.append(f"data 'CJKT' ({res_id}, \"{name}\") {{")
        for i in range(0, len(data), 32):
            parts.append(f'\t$"{data[i:i + 32].hex().upper()}"')
        parts.append("};")
        parts.append("")
        print(f"{name}: {len(pairs)} characters, {len(data)} bytes, 'CJKT' {res_id}")
    with open(out, "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    sys.exit(main())
