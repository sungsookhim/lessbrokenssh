#!/usr/bin/env python3
"""Regenerate libvterm/src/fullwidth.inc: the characters that take 2 cells.

That's every character whose East Asian Width is Wide or Fullwidth, from
this Python's Unicode database (Python 3.14 has Unicode 16.0). Since Unicode 9
that includes emoji with emoji presentation, so the table agrees with how
the Claude CLI (string-width) and current glibc measure text.

Run it with the newest Python you have, then rebuild:

    python3 tools/unicode/gen_fullwidth.py
"""

import os
import sys
import unicodedata

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "libvterm", "src", "fullwidth.inc")


def wide_ranges():
    ranges = []
    for cp in range(0x110000):
        if unicodedata.east_asian_width(chr(cp)) not in ("W", "F"):
            continue
        if ranges and ranges[-1][1] == cp - 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    return ranges


def main():
    ranges = wide_ranges()
    with open(OUT, "w") as f:
        f.write(f"  /* generated by tools/unicode/gen_fullwidth.py from Unicode {unicodedata.unidata_version} */\n")
        for lo, hi in ranges:
            f.write(f"  {{ 0x{lo:04x}, 0x{hi:04x} }},\n")
    print(f"Unicode {unicodedata.unidata_version}: {len(ranges)} ranges -> {OUT}")


if __name__ == "__main__":
    sys.exit(main())
